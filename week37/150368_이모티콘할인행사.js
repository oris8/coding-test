/**
 * 1.이모티콘 플러스 서비스 가입자를 최대한 늘리는 것.
 * 2. 이모티콘 판매액을 최대한 늘리는 것.
 * 와 같은 우선 순위를 가지고,
 * 행사 목적을 최대한으로 달성했을 때의 이모티콘 플러스 서비스 가입 수와 이모티콘 매출액 구하기
 *
 * @param {*} users - [discountRate, budget][]
 * @param {*} emoticons - [price][]
 * @return [이모티콘 플러스 서비스 가입 수, 이모티콘 매출액]
 */
function solution(users, emoticons) {
  const 할인율 = [10, 20, 30, 40]; // 가능한 할인율
  let 최적_이모티콘_플러스_서비스_가입_수 = 0;
  let 최적_이모티콘_매출액 = 0;

  // 이모티콘의 개수만큼 가능한 할인율을 모두 조합
  function dfs(index, 할인율조합) {
    if (index === emoticons.length) {
      let 이모티콘_플러스_서비스_가입_수 = 0;
      let 이모티콘_매출액 = 0;

      // 각 사용자의 구매 여부를 계산
      users.forEach((user) => {
        const [할인기준, 예산] = user;
        let 총_구매액 = 0;

        // 이모티콘에 대한 할인율 계산
        for (let i = 0; i < emoticons.length; i++) {
          const 원가 = emoticons[i];
          const 적용된_할인율 = 할인율조합[i];
          if (적용된_할인율 >= 할인기준) {
            총_구매액 += 원가 * (1 - 적용된_할인율 / 100);
          }
        }

        // 플러스 서비스 가입 여부 판단
        if (총_구매액 >= 예산) {
          이모티콘_플러스_서비스_가입_수++;
        } else {
          이모티콘_매출액 += 총_구매액;
        }
      });

      // 현재 조합에 대해 최적의 값인지 확인
      if (
        이모티콘_플러스_서비스_가입_수 > 최적_이모티콘_플러스_서비스_가입_수
      ) {
        최적_이모티콘_플러스_서비스_가입_수 = 이모티콘_플러스_서비스_가입_수;
        최적_이모티콘_매출액 = 이모티콘_매출액;
      } else if (
        이모티콘_플러스_서비스_가입_수 === 최적_이모티콘_플러스_서비스_가입_수
      ) {
        최적_이모티콘_매출액 = Math.max(최적_이모티콘_매출액, 이모티콘_매출액);
      }

      return;
    }

    // 각 이모티콘에 대해 할인율을 하나씩 시도
    for (let i = 0; i < 할인율.length; i++) {
      할인율조합[index] = 할인율[i];
      dfs(index + 1, 할인율조합);
    }
  }

  dfs(0, Array(emoticons.length).fill(0));

  return [최적_이모티콘_플러스_서비스_가입_수, 최적_이모티콘_매출액];
}
